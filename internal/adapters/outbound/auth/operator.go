package auth

import (
	"context"
	"crypto/rand"
	"crypto/subtle"
	"encoding/base64"
	"fmt"
	"strings"
	"unicode/utf8"

	"golang.org/x/crypto/argon2"

	"socketfabric/internal/application/ports"
	"socketfabric/internal/domain"
)

// Passwords bounds expensive work independently of HTTP request concurrency.
type Passwords struct{ slots chan struct{} }

var _ ports.PasswordHasher = (*Passwords)(nil)

func NewPasswords() *Passwords { return &Passwords{slots: make(chan struct{}, 4)} }

func (p *Passwords) acquire(ctx context.Context) error {
	if err := ctx.Err(); err != nil {
		return err
	}
	select {
	case p.slots <- struct{}{}:
		return nil
	default:
		return domain.ErrRateLimited
	}
}
func (p *Passwords) Hash(ctx context.Context, password string) (string, error) {
	if !utf8.ValidString(password) || utf8.RuneCountInString(password) < 15 || utf8.RuneCountInString(password) > 128 || strings.ContainsRune(password, 0) {
		return "", domain.ErrInvalid
	}
	if err := p.acquire(ctx); err != nil {
		return "", err
	}
	defer func() { <-p.slots }()
	var salt [16]byte
	if _, err := rand.Read(salt[:]); err != nil {
		return "", domain.ErrUnavailable
	}
	hash := argon2.IDKey([]byte(password), salt[:], 2, 19*1024, 1, 32)
	if err := ctx.Err(); err != nil {
		return "", err
	}
	return "$argon2id$v=19$m=19456,t=2,p=1$" + base64.RawStdEncoding.EncodeToString(salt[:]) + "$" + base64.RawStdEncoding.EncodeToString(hash), nil
}
func (p *Passwords) Verify(ctx context.Context, encoded, password string) error {
	if len(password) > 512 {
		return domain.ErrUnauthorized
	}
	parts := strings.Split(encoded, "$")
	// Only parameters generated by this implementation are admitted; never let
	// a malformed DB record allocate attacker-selected memory/CPU resources.
	if len(parts) != 6 || parts[1] != "argon2id" || parts[2] != "v=19" || parts[3] != "m=19456,t=2,p=1" {
		return domain.ErrUnauthorized
	}
	salt, err := base64.RawStdEncoding.DecodeString(parts[4])
	if err != nil || len(salt) != 16 {
		return domain.ErrUnauthorized
	}
	want, err := base64.RawStdEncoding.DecodeString(parts[5])
	if err != nil || len(want) != 32 {
		return domain.ErrUnauthorized
	}
	if err := p.acquire(ctx); err != nil {
		return err
	}
	defer func() { <-p.slots }()
	got := argon2.IDKey([]byte(password), salt, 2, 19*1024, 1, 32)
	if err := ctx.Err(); err != nil {
		return err
	}
	if subtle.ConstantTimeCompare(want, got) != 1 {
		return fmt.Errorf("password authentication failed: %w", domain.ErrUnauthorized)
	}
	return nil
}
